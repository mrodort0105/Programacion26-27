package com.mycompany.programacion;

import java.util.Scanner;

/**
 *
 * @author 18_1DAW
 */
public class ContarNumero {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int n1 = scanner.nextInt();
        int contador = 1;
        while (contador <= n1 ) {
            contador = contador + 1;
        }
    }
}
            
